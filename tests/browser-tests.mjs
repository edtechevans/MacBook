import assert from "node:assert/strict";
import {mkdirSync} from "node:fs";
import {chromium} from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
const base="http://127.0.0.1:8080/";
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const context=await browser.newContext({viewport:{width:1370,height:900}});
const page=await context.newPage();
const errors=[];
mkdirSync("test-artifacts",{recursive:true});
page.on("pageerror",e=>errors.push(e.message));
async function check(condition,message){assert(condition,message);console.log("PASS: "+message);}
try {
  await page.goto(base,{waitUntil:"networkidle"});
  await check(await page.locator("#hero-title").isVisible(),"Homepage and hero render");
  await page.screenshot({path:"test-artifacts/homepage-desktop.png",fullPage:true});
  await check(await page.locator("#category-grid .category-card").count()===4,"All four application categories render");
  await check(await page.locator("#popular-list button").count()===4,"Quick tasks are working buttons");
  await check((await page.locator("#result-count").textContent()).includes("55 lessons"),"All 55 lessons available");
  const accessibility=await new AxeBuilder({page}).withTags(["wcag2a","wcag2aa","wcag21aa","wcag22aa"]).analyze();
  await check(accessibility.violations.length===0,"Homepage WCAG 2.2 AA axe checks: "+accessibility.violations.map(x=>x.id+" "+x.description).join("; "));
  await page.locator("#hero-query").fill("record my screen");
  await page.locator("#hero-search button").click();
  await check((await page.locator("#result-count").textContent()).includes("lesson"),"Natural-language task search returns results");
  await check(await page.locator('#tips-grid [data-tip="t22"]').count()===1,"Screen recording lesson found");
  await page.locator('#tips-grid [data-tip="t22"]').click();
  await check(await page.locator("#lesson-dialog").isVisible(),"Guided lesson opens");
  await check((await page.locator("#lesson-title").textContent()).includes("record your screen"),"Correct lesson opens");
  await check(await page.locator(".visual-map").isVisible(),"Guided lesson includes visual location map");
  await page.screenshot({path:"test-artifacts/guided-lesson-desktop.png"});
  await check((await page.locator(".visual-caption").textContent()).includes("not a screenshot"),"Illustrations are correctly labelled");
  await check(await page.locator("#step-prev").isDisabled(),"Step 1 has disabled previous control");
  for(let i=0;i<3;i++)await page.locator("#step-next").click();
  await check((await page.locator("#step-heading").textContent()).includes("Try it"),"Guided lesson reaches real practice");
  await page.locator('[data-outcome="worked"]').click();
  await check((await page.locator("#lesson-feedback").textContent()).includes("completed"),"Practice completion provides feedback");
  const modalAxe=await new AxeBuilder({page}).withTags(["wcag2a","wcag2aa","wcag21aa","wcag22aa"]).analyze();
  await check(modalAxe.violations.length===0,"Walkthrough dialog WCAG 2.2 AA axe checks: "+modalAxe.violations.map(x=>x.id).join(", "));
  await page.goBack({waitUntil:"domcontentloaded"});
  await check(!(await page.locator("#lesson-dialog").isVisible()),"Browser Back closes walkthrough rather than leaving site");
  await page.reload();
  await check((await page.locator("#progress-count").textContent()).includes("1"),"Completed progress persists after refresh");
  await page.locator('#category-filters [data-filter="Teams"]').click();
  await check((await page.locator("#result-count").textContent()).includes("7 lessons"),"Application filtering works");
  await page.locator("#clear-filters").click();
  await page.locator('#tips-grid [data-save="t16"]').click();
  await check((await page.locator('#tips-grid [data-save="t16"]').getAttribute("aria-pressed"))==="true","Favourites have accessible pressed state");
  await page.locator("#saved-only").check();
  await check((await page.locator("#result-count").textContent()).includes("1 lesson"),"Saved-only filter works");
  await page.locator("#clear-filters").click();
  await page.locator("#mode-quick").count();
  await page.locator("#quiz-options [data-quiz-choice='0']").click();
  await check(!(await page.locator("#quiz-next").isDisabled()),"Quiz enables progression after answer");
  for(const answer of [1,2,1,0,1,2,0]){await page.locator("#quiz-next").click();await page.locator('#quiz-options [data-quiz-choice="'+answer+'"]').click();}
  await page.locator("#quiz-next").click();
  await check((await page.locator("#quiz-score").textContent()).includes("8 of 8"),"Quiz result is scored correctly");
  await page.locator("#quiz-restart").click();
  await check((await page.locator("#quiz-progress").textContent())==="1 / 8","Quiz can restart");
  await page.locator("#language").selectOption("zh");
  await check((await page.locator("#hero-title").textContent()).includes("自信"),"Chinese navigation translations work");
  await page.locator("#language").selectOption("en");
  await page.setViewportSize({width:375,height:812});
  await check(await page.locator("#menu-toggle").isVisible(),"Phone navigation adapts");
  await page.screenshot({path:"test-artifacts/homepage-mobile.png",fullPage:true});
  await page.locator("#menu-toggle").click();
  await check(await page.locator("#main-nav").isVisible(),"Mobile navigation opens");
  await page.locator("#menu-toggle").click();
  const width=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,view:window.innerWidth}));
  await check(width.scroll<=width.view+2,"No horizontal scrolling at 375px viewport: "+JSON.stringify(width));
  await page.locator("#popular-list [data-tip='t22']").click();
  await check(await page.locator("#lesson-dialog").isVisible(),"Phone lesson opens");
  await page.screenshot({path:"test-artifacts/guided-lesson-mobile.png"});
  const dialogSize=await page.locator("#lesson-dialog").boundingBox();
  await check(dialogSize.width<=377&&dialogSize.height<=814,"Mobile dialog fits viewport");
  await page.locator("#mode-quick").click();
  await check(await page.locator("#quick-panel").isVisible(),"Quick-answer mode works");
  await page.locator("#lesson-close").click();
  await page.goto(base+"print.html?tip=t22");
  await check((await page.locator("#print-lessons").textContent()).includes("Capture or record your screen"),"Full printable individual walkthrough");
  await page.goto(base+"print.html");
  await check(await page.locator(".tip").count()===55,"Printable guide contains all 55 complete tips");
  await check(errors.length===0,"No uncaught browser JavaScript errors: "+errors.join(" | "));
  console.log("ALL END-TO-END BROWSER TESTS PASSED.");
} finally {await browser.close();}
